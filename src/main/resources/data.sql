INSERT INTO preventives (
    preventive_plan_assignment_id,
    plan_name,
    plan_description,
    assigned_inspector_id,
    due_date,
    status,
    work_performed,
    assigned_at,
    started_at,
    completed_at,
    created_at,
    updated_at
)
SELECT
    assignment.id,
    plan.name,
    plan.description,
    CASE MOD(machine.id, 4)
        WHEN 0 THEN NULL
        ELSE 4 + MOD(machine.id - 1, 5)
    END,
    CASE MOD(machine.id, 4)
        WHEN 3 THEN DATEADD('DAY', -MOD(machine.id, 8) - 2, CURRENT_DATE)
        ELSE CASE MOD(machine.id, 6)
            WHEN 0 THEN DATEADD('DAY', -6, CURRENT_DATE)
            WHEN 1 THEN DATEADD('DAY', -2, CURRENT_DATE)
            WHEN 2 THEN DATEADD('DAY', -1, CURRENT_DATE)
            WHEN 3 THEN CURRENT_DATE
            WHEN 4 THEN DATEADD('DAY', 1, CURRENT_DATE)
            ELSE DATEADD('DAY', 2, CURRENT_DATE)
        END
    END,
    CASE MOD(machine.id, 4)
        WHEN 0 THEN 'PENDING'
        WHEN 1 THEN 'ASSIGNED'
        WHEN 2 THEN 'IN_PROGRESS'
        ELSE 'COMPLETED'
    END,
    CASE WHEN MOD(machine.id, 4) = 3
        THEN 'Trabajo preventivo completado y verificado conforme a la plantilla.'
        ELSE NULL
    END,
    CASE WHEN MOD(machine.id, 4) = 0 THEN NULL ELSE DATEADD('DAY', -7, CURRENT_TIMESTAMP) END,
    CASE WHEN MOD(machine.id, 4) IN (2, 3) THEN DATEADD('DAY', -3, CURRENT_TIMESTAMP) ELSE NULL END,
    CASE WHEN MOD(machine.id, 4) = 3 THEN DATEADD('DAY', -1, CURRENT_TIMESTAMP) ELSE NULL END,
    CURRENT_TIMESTAMP,
    CURRENT_TIMESTAMP
FROM preventive_plan_assignments AS assignment
JOIN preventive_plans AS plan ON plan.id = assignment.preventive_plan_id
JOIN machines AS machine ON machine.id = assignment.machine_id
WHERE machine.id BETWEEN 1 AND 12
  AND assignment.active = TRUE;
